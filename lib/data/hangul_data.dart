class HangulLetter {
  final String letter; // e.g. 'ㄱ'
  final String name; // e.g. '기역'
  final String sound; // e.g. '[g / k]'
  final String soundTip; // English phonetic tip e.g. 'g like in "go"'
  final String categoryType; // 'plain' (평음), 'aspirated' (격음), 'tense' (경음), 'vowel' (모음)
  final String exampleKorean; // e.g. '가방'
  final String exampleRoman; // e.g. 'gabang'
  final Map<String, String> exampleMeanings; // translations for the 7 languages
  final String emoji; // 0-byte Unicode emoji

  const HangulLetter({
    required this.letter,
    required this.name,
    required this.sound,
    required this.soundTip,
    required this.categoryType,
    required this.exampleKorean,
    required this.exampleRoman,
    required this.exampleMeanings,
    required this.emoji,
  });

  String getMeaning(String langCode) {
    return exampleMeanings[langCode] ?? exampleMeanings['EN'] ?? exampleKorean;
  }

  String getSoundTip(String langCode) {
    return HangulData.localizedSoundTips[letter]?[langCode] ??
        HangulData.localizedSoundTips[letter]?['EN'] ??
        soundTip;
  }
}

class DiscoveredWord {
  final String word;
  final String emoji;
  final String roman;
  final Map<String, String> meanings;

  const DiscoveredWord({
    required this.word,
    required this.emoji,
    required this.roman,
    required this.meanings,
  });

  String getMeaning(String langCode) => meanings[langCode] ?? meanings['EN'] ?? word;
}

