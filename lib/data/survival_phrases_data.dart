  /// Returns today's survival phrase based on days since epoch.
  /// Automatically shifts to the next phrase every midnight.
  static SurvivalPhraseItem getTodayPhrase() {
    final now = DateTime.now();
    final daysSinceStart = DateTime(now.year, now.month, now.day)
        .difference(DateTime(2025, 1, 1))
        .inDays;
    final index = daysSinceStart.abs() % phrases.length;
    return phrases[index];
  }
