  /// Translate a key with fallback hierarchy: [langCode] -> 'EN' -> 'KO'
  static String tr(String key, String langCode, [Map<String, String>? params]) {
    final lang = langCode.toUpperCase();
    final langMap = _localizedValues[lang] ??
        _localizedValues['EN'] ??
        _localizedValues['KO']!;
    var text = langMap[key] ??
        _localizedValues['EN']?[key] ??
        _localizedValues['KO']?[key] ??
        key;

    if (params != null && params.isNotEmpty) {
      params.forEach((placeholder, value) {
        text = text.replaceAll('{$placeholder}', value);
      });
    }
    return text;
  }

