  /// Translate a key with fallback hierarchy: [langCode] -> 'EN' -> 'KO'
  static String tr(String key, String langCode, [Map<String, String>? params]) {
    final lang = langCode.toUpperCase();
    final langMap = _localizedValues[lang] ??
        _localizedValues['EN'] ??
        _localizedValues['KO']!;
    var text = langMap[key] ??
        _localizedValues['EN']?[key] ??
        _localizedValues['KO']?[key] ??
        key;

    if (params != null && params.isNotEmpty) {
      params.forEach((placeholder, value) {
        text = text.replaceAll('{$placeholder}', value);
      });
    }
    return text;
  }

  /// Localize category name
  static String category(String categoryKey, String langCode) {
    switch (categoryKey) {
      case 'Honorifics':
        return tr('cat_honorifics', langCode);
      case 'Particles':
        return tr('cat_particles', langCode);
      case 'Real-life':
        return tr('cat_real_life', langCode);
      case 'Nuances':
      case 'Nuance':
        return tr('cat_nuances', langCode);
      case 'Grammar':
        return tr('cat_grammar', langCode);
      case 'Practical':
        return tr('cat_practical', langCode);
      case 'Objects':
        return tr('cat_objects', langCode);
      case 'Health':
        return tr('cat_health', langCode);
      case 'Antonyms':
        return tr('cat_antonyms', langCode);
      case 'Personality':
        return tr('cat_personality', langCode);
      default:
        return categoryKey;
    }
  }
